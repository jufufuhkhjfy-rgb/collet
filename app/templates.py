HASHTAGS = {
    "100804": ["#インテリア", "#お部屋づくり", "#一人暮らし"],
    "215783": ["#便利グッズ", "#暮らしを整える"],
    "216131": ["#バッグ", "#小物"],
    "551177": ["#メンズファッション", "#プチプラコーデ"],
    "558885": ["#スニーカー", "#靴"],
    "100371": ["#レディースファッション", "#プチプラ"],
    "100026": ["#デスク周り", "#PC周辺機器", "#ガジェット"],
    "564500": ["#スマホグッズ", "#ガジェット"],
    "211742": ["#オーディオ", "#ガジェット"],
}

_GROUP_OF = {g["id"]: group["name"] for group in GENRE_GROUPS for g in group["genres"]}


def template_comment(item: dict) -> str:
    group = _GROUP_OF.get(item["genre_id"], "雑貨")
    lines = [random.choice(OPENERS[group])]

    if item["review_count"] >= 10:
        lines.append(f"レビューは★{item['review_average']:.1f}（{item['review_count']:,}件）と評価も高めです。")

    price = item["price"]
    if price <= 3000:
        lines.append(f"{price:,}円と、気軽に手が届く価格なのもうれしいポイント。")
    elif price <= 8000:
        lines.append(f"{price:,}円で、この評価ならコスパは良さそうです。")
    else:
        lines.append(f"{price:,}円。長く使えるものを探している人におすすめです。")

    tags = HASHTAGS.get(item["genre_id"], [])[:3] + ["#コスパ"]
    return "\n".join(lines) + "\n\n" + " ".join(tags)
